    // -----------------------------------------------------------------------------
    // Scalar reference implementation: 1:1 port of ppp/cryptography/ssea.cpp
    // base94_encode / base94_decode (semantics of the openppp2 ssea module).
    // Used as the correctness baseline for the SIMD variants.
    // -----------------------------------------------------------------------------

    constexpr int BASE94_SYMBOL_COUNT = 94;   ///< Number of symbols in Base94 alphabet
    constexpr int BASE94_INPUT_BLOCK_SIZE = 9; ///< Optimal input block size (bytes)
    constexpr int BASE94_OUTPUT_BLOCK_SIZE = 11; ///< Optimal output block size (chars)
    constexpr int BASE93_RADIX = BASE94_SYMBOL_COUNT - 1; ///< 93

    /**
     * @brief Encodes binary bytes with the project-specific Base94 mapping.
     * @param data    Input bytes (must be non-null, datalen >= 1).
     * @param datalen Number of input bytes.
     * @param kf      Per-byte offset subtracted before mapping.
     * @param output  [out] Receives the allocated encoded buffer.
     * @return Encoded byte count, or 0 on failure.
     */
    inline int base94_encode_scalar(const void* data, int datalen, int kf, std::unique_ptr<uint8_t[]>& output) noexcept
    {
        const uint8_t* bytes = static_cast<const uint8_t*>(data);
        if (nullptr == bytes || datalen < 1)
        {
            return 0;
        }

        // First pass: compute the length of the encoded string.
        int bucket_length = 0;
        for (int i = 0; i < datalen; i++)
        {
            const uint8_t b = static_cast<uint8_t>(bytes[i] - kf);
            bucket_length += (b >= BASE93_RADIX) ? 2 : 1;
        }

        output = std::make_unique<uint8_t[]>(bucket_length + 16); // +16 slack for SIMD-safe writes
        uint8_t* bucket = output.get();
        for (int i = 0; i < datalen; i++)
        {
            const uint8_t b = static_cast<uint8_t>(bytes[i] - kf);
            if (b >= BASE93_RADIX)
            {
                *bucket++ = static_cast<uint8_t>('\x20' + (((b / BASE93_RADIX) - 1) + BASE93_RADIX));
                *bucket++ = static_cast<uint8_t>('\x20' + (b % BASE93_RADIX));
            }
            else
            {
                *bucket++ = static_cast<uint8_t>('\x20' + b);
            }
        }

        return bucket_length;
    }

    /**
     * @brief Decodes bytes generated by base94_encode_scalar.
     * @param data    Encoded Base94 byte sequence.
     * @param datalen Number of encoded input bytes.
     * @param kf      Per-byte offset added back after decoding.
     * @param output  [out] Receives the allocated decoded buffer.
     * @return Decoded byte count, or 0 on failure (invalid input).
     */
    inline int base94_decode_scalar(const void* data, int datalen, int kf, std::unique_ptr<uint8_t[]>& output) noexcept
    {
        const uint8_t* bytes = static_cast<const uint8_t*>(data);
        if (nullptr == bytes || datalen < 1)
        {
            return 0;
        }

        // First pass: validate input and compute output length.
        int bucket_length = datalen;
        for (int i = 0; i < datalen; i++)
        {
            uint8_t b = bytes[i];
            if (b < '\x20')
            {
                return 0;   // Character below printable range
            }

            b -= '\x20';
            if (b > BASE94_SYMBOL_COUNT)
            {
                return 0;   // Character beyond the 94 symbols
            }

            if (b >= BASE93_RADIX)
            {
                // Two-character escape; next character must exist.
                if (++i < datalen)
                {
                    b = bytes[i];
                    if (b < '\x20')
                    {
                        return 0;
                    }

                    b -= '\x20';
                    if (b > BASE93_RADIX)
                    {
                        return 0;
                    }
                }
                else
                {
                    return 0;   // Unexpected end of string
                }

                bucket_length--;
            }
        }

        output = std::make_unique<uint8_t[]>(bucket_length + 16);
        uint8_t* bucket = output.get();
        for (int i = 0; i < datalen; i++)
        {
            const uint8_t b = bytes[i] - '\x20';
            if (b >= BASE93_RADIX)
            {
                const int v = (((b - BASE93_RADIX) + 1) * BASE93_RADIX) + (bytes[++i] - '\x20');
                if (v > 0xff)
                {
                    return 0;   // Decoded value out of byte range
                }

                *bucket++ = static_cast<uint8_t>(v + kf);
            }
            else
            {
                *bucket++ = static_cast<uint8_t>(b + kf);
            }
        }

        return bucket_length;
    }

